class LockTests(OfflineCase):
    def test_seed_validation_covers_graph_sri_origins_and_versions(self):
        value = registry()
        raw.validate_seed(seed(value), value)
        self.assertEqual(set(raw.lock_blocks(seed(value))), {raw.LEAF + "@1.0.0", raw.PARENT + "@1.0.0"})

    def test_missing_lock_is_absence_not_empty_bytes(self):
        self.assertIsNone(raw.mutate_lock(seed(), "YF002-missing-lock"))

    def test_incomplete_lock_removes_only_leaf_block(self):
        original = raw.lock_blocks(seed())
        mutated = raw.lock_blocks(raw.mutate_lock(seed(), "YF006-incomplete-transitive"))
        self.assertEqual(mutated, {raw.PARENT + "@1.0.0": original[raw.PARENT + "@1.0.0"]})
        self.assertIn('    ' + raw.LEAF + ' "1.0.0"', next(iter(mutated.values())))

    def test_wrong_integrity_is_valid_sha512_not_malformed(self):
        changed = raw.mutate_lock(seed(), "YF004-wrong-sri")
        original_blocks, changed_blocks = raw.lock_blocks(seed()), raw.lock_blocks(changed)
        self.assertEqual(original_blocks[raw.PARENT + "@1.0.0"], changed_blocks[raw.PARENT + "@1.0.0"])
        leaf_before, leaf_after = (blocks[raw.LEAF + "@1.0.0"] for blocks in (original_blocks, changed_blocks))
        for field in ("version", "resolved"):
            self.assertEqual(raw.lock_field(leaf_before, field), raw.lock_field(leaf_after, field))
        algorithm, encoded = raw.lock_field(leaf_after, "integrity").split("-", 1)
        self.assertEqual(algorithm, "sha512")
        self.assertEqual(base64.b64decode(encoded, validate=True), bytes(64))

    def test_other_cases_preserve_lock_bytes(self):
        for case in set(raw.CASES) - {"YF002-missing-lock", "YF004-wrong-sri", "YF006-incomplete-transitive"}:
            with self.subTest(case=case):
                self.assertEqual(raw.mutate_lock(seed(), case), seed())

    def test_seed_validation_rejects_changed_origin_sri_version_and_incomplete_graph(self):
        value = registry()
        original = seed(value)
        for wrong in (original.replace("127.0.0.1", "example.invalid"),
                      original.replace('version "1.0.0"', 'version "2.0.0"', 1),
                      raw.mutate_lock(original, "YF004-wrong-sri"),
                      raw.mutate_lock(original, "YF006-incomplete-transitive")):
            with self.subTest(wrong=raw.digest(wrong.encode())), self.assertRaises(ValueError):
                raw.validate_seed(wrong, value)

    def test_reject_bad_header_crlf_size_duplicate_and_unknown_keys(self):
        original = seed()
        for wrong in (original.replace("# yarn lockfile v1", "# yarn lockfile v2"),
                      original.replace("\n", "\r\n"), "x" * (1024 * 1024 + 1),
                      original + raw.lock_blocks(original)[raw.LEAF + "@1.0.0"],
                      original.replace(raw.LEAF + "@1.0.0:", "external@1.0.0:"), "# yarn lockfile v1\n"):
            with self.subTest(wrong=raw.digest(wrong.encode())), self.assertRaises(ValueError):
                raw.lock_blocks(wrong)

    def test_lock_field_rejects_missing_or_duplicate(self):
        with self.assertRaises(ValueError):
            raw.lock_field("abc:\n", "integrity")
        with self.assertRaises(ValueError):
            raw.lock_field("abc:\n  version a\n  version b\n", "version")

    def test_unknown_case_and_quoted_seed_keys(self):
        with self.assertRaises(ValueError):
            raw.mutate_lock(seed(), "../arbitrary")
        quoted = seed().replace(raw.LEAF + "@1.0.0:", json.dumps(raw.LEAF + "@1.0.0") + ":")
        raw.validate_seed(quoted, registry())


