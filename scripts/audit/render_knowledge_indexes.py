#!/usr/bin/env python3
"""Render complete finding/backlog indexes from reviewed data; no network writes."""
from __future__ import annotations
from collections import Counter
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRIORITY = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}
PHASES = {0: "Migration remediation already verified", 1: "Before a supported preview", 2: "Compatibility, robustness and performance", 3: "Breadth, polish and longer-term design"}
AREAS = {"BUILD": "Build and supply chain", "IO": "Files, picker and Coil", "NATIVE": "WebView, camera and sharing", "NAV": "Core, navigation, icons and samples", "PERM": "Permissions and geo", "UI": "Adaptive controls and UIKit"}


def main():
    findings = [f for p in sorted((ROOT / "docs/audit/findings").glob("*.json")) for f in json.loads(p.read_text())]
    by_id = {f["id"]: f for f in findings}
    resolutions = json.loads((ROOT / "docs/audit/migration-resolutions.json").read_text())
    plan = json.loads((ROOT / "docs/audit/issue-plan.json").read_text())
    mapping_file = ROOT / "docs/migration/issue-map.json"
    mapping = json.loads(mapping_file.read_text()) if mapping_file.exists() else {"items": [], "complete": False}
    remote = {item["key"]: item for item in mapping["items"]}
    def link(key, prefix="../audit/"):
        item = remote.get(key)
        return f'[#'+str(item["number"])+']('+item["url"]+')' if item else f'[draft]({prefix}issue-drafts/{key.replace(":", "-")}.md)'
    phases = {}
    for f in findings:
        phases[f["id"]] = 0 if f["id"] in resolutions else (1 if f["priority"] in {"Critical", "High"} or f["id"].startswith("BUILD-") else 2 if f["priority"] == "Medium" else 3)
    # Prerequisites must be scheduled no later than the work they unblock.
    changed = True
    while changed:
        changed = False
        for f in findings:
            for dep in f["dependencies"]:
                if dep not in by_id: raise ValueError("Unknown dependency: " + dep)
                if phases[dep] > phases[f["id"]]: phases[dep] = phases[f["id"]]; changed = True
    remaining, ordered = set(by_id), []
    while remaining:
        ready = [by_id[key] for key in remaining if not (set(by_id[key]["dependencies"]) & remaining)]
        if not ready: raise ValueError("Dependency cycle")
        ready.sort(key=lambda f: (phases[f["id"]], PRIORITY[f["priority"]], f["id"]))
        item = ready[0]; ordered.append(item); remaining.remove(item["id"])
    summary = {"baseline": plan["baseline"], "findings": len(findings), "priorities": {p: sum(f["priority"] == p for f in findings) for p in PRIORITY}, "evidence_statuses": dict(sorted(Counter(f["status"] for f in findings).items())), "effort": dict(sorted(Counter(f["effort"] for f in findings).items())), "baseline_findings_resolved_in_migration": sorted(resolutions), "planned_issues": plan["count"], "remote_map_complete": mapping.get("complete", False), "mapped_issues": len(remote), "areas": {area: dict(Counter(f["priority"] for f in findings if f["id"].startswith(area + "-"))) for area in AREAS}}
    (ROOT / "docs/audit/summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    lines = ["# Complete finding index", "", "Generated by `scripts/audit/render_knowledge_indexes.py`. Baseline citations and full root cause, impact, fix, risks and required tests are in the linked JSON and area reports. Evidence classes are defined in [the audit](README.md). Priority is not a vulnerability score. Source-confirmed is not device-tested.", "", "| ID | Priority | Evidence | Finding | Issue |", "|---|---|---|---|---|"]
    for f in sorted(findings, key=lambda f: (PRIORITY[f["priority"]], f["id"])):
        area = f["id"].split("-")[0]
        resolved = " **(migration-resolved)**" if f["id"] in resolutions else ""
        title = f["title"].replace("|", "\\|")
        lines.append(f'| [{f["id"]}](findings/{area}.json) | {f["priority"]} | `{f["status"]}` | {title}{resolved} | {link("audit:"+f["id"], "")} |')
    (ROOT / "docs/audit/findings-index.md").write_text("\n".join(lines) + "\n")
    backlog = []
    for order, f in enumerate(ordered, 1):
        key = "audit:" + f["id"]
        backlog.append({"order": order, "key": key, "finding": f["id"], "title": f["title"], "phase": phases[f["id"]], "priority": f["priority"], "evidence_status": f["status"], "effort": f["effort"], "dependencies": f["dependencies"], "modules": f["modules"], "workstream": AREAS[f["id"].split("-")[0]], "state": remote.get(key, {}).get("actual_state", "closed" if f["id"] in resolutions else "open"), "issue_url": remote.get(key, {}).get("url"), "required_tests": f["required_tests"]})
    for item in plan["items"]:
        if item["finding_ids"]: continue
        priority = next(x.split(":")[1].capitalize() for x in item["labels"] if x.startswith("priority:"))
        backlog.append({"order": len(backlog) + 1, "key": item["key"], "title": item["title"], "phase": 2 if priority in {"High", "Medium", "Critical"} else 3, "priority": priority, "evidence_status": next(x.split(":")[1] for x in item["labels"] if x.startswith("evidence:")), "effort": "triage-first", "dependencies": [], "upstream_numbers": item["upstream_numbers"], "workstream": "Actionable historical requests", "state": remote.get(item["key"], {}).get("actual_state", "open"), "issue_url": remote.get(item["key"], {}).get("url"), "required_tests": ["Reproduce current behavior or define scoped platform acceptance criteria before implementation."]})
    output = {"baseline": plan["baseline"], "ordering": "Dependency-respecting suggested order, not an owner-approved schedule; prerequisites may have lower severity.", "phases": PHASES, "items": backlog}
    (ROOT / "docs/roadmap/backlog.json").write_text(json.dumps(output, indent=2) + "\n")
    lines = ["# Complete ordered backlog", "", "Generated from every audit finding plus actionable historical requests. See [roadmap strategy](README.md), [machine-readable tests/dependencies](backlog.json), and [finding detail](../audit/findings-index.md). State is the last synchronized observation, not a live tracker.", ""]
    for phase, title in PHASES.items():
        lines += [f"## {phase}. {title}", "", "| Order | Finding / topic | Priority | Effort | Dependencies | State | Issue |", "|---:|---|---|---|---|---|---|"]
        for item in backlog:
            if item["phase"] != phase: continue
            name = item.get("finding", "Upstream " + ", ".join("#"+str(n) for n in item.get("upstream_numbers", [])))
            title = item["title"].replace("|", "\\|")
            lines.append(f'| {item["order"]} | **{name}** — {title} | {item["priority"]} | {item["effort"]} | {", ".join(item["dependencies"]) or "—"} | {item["state"]} | {link(item["key"])} |')
        lines.append("")
    (ROOT / "docs/roadmap/backlog.md").write_text("\n".join(lines).rstrip() + "\n")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
