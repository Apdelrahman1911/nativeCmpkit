def registry() -> raw.Registry:
    value = raw.Registry()  # Construction only; never bind/listen in unit tests.
    value.base = "http://127.0.0.1:45123/registry"
    return value


def seed(value: raw.Registry | None = None) -> str:
    value = value or registry()
    result = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"
    for name in (raw.LEAF, raw.PARENT):
        data = value.packages[(name, "1.0.0")]
        result += (name + '@1.0.0:\n  version "1.0.0"\n  resolved '
                   + json.dumps(value.url(name, "1.0.0") + "#" + raw.digest(data, "sha1"))
                   + "\n  integrity " + raw.sri(data) + "\n")
        if name == raw.PARENT:
            result += '  dependencies:\n    ' + raw.LEAF + ' "1.0.0"\n'
        result += "\n"
    return result


def integrity_message(data: bytes) -> str:
    return ('Integrity check failed for ' + json.dumps(raw.LEAF)
            + " (computed integrity doesn't match our records, got "
            + json.dumps(raw.sri(data) + " " + raw.sri(data, "sha1")) + ")")


